#!/usr/bin/env node
// Copies the real `dbops health` runs from ../dbops-lab/results/ into src/data/terminal.ts,
// so the operations terminal on the site replays measured output, not a mock.
//
// Usage: node scripts/build-terminal.mjs [path-to-dbops-lab]
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const lab = resolve(process.argv[2] ?? "../dbops-lab");
const out = resolve("src/data/terminal.ts");

function readRun(file) {
  const raw = readFileSync(join(lab, "results", file), "utf8").replace(/\r\n/g, "\n").trimEnd();
  const lines = raw.split("\n");
  // The first lines are '#' comments describing the run; keep them apart from the output.
  const notes = [];
  while (lines.length && lines[0].startsWith("#")) notes.push(lines.shift().replace(/^#\s?/, ""));
  while (lines.length && lines[0].trim() === "") lines.shift();
  const verdictLine = lines[lines.length - 1];
  const verdict = verdictLine.split(/\s+/)[0];
  return { notes, lines, verdict, verdictLine };
}

const runs = [
  { id: "faults", label: "Four faults injected", file: "m2-health-faults.txt", exitCode: 2 },
  { id: "healthy", label: "Healthy lab", file: "m2-health-ok.txt", exitCode: 0 },
].map((run) => ({ ...run, ...readRun(run.file) }));

const body = `// Generated by scripts/build-terminal.mjs from ../dbops-lab/results/. Do not edit by hand.

export type TerminalRun = {
  id: string;
  label: string;
  file: string;
  exitCode: number;
  notes: string[];
  lines: string[];
  verdict: string;
  verdictLine: string;
};

export const terminalRuns: TerminalRun[] = ${JSON.stringify(runs, null, 2)};
`;

writeFileSync(out, body);
console.log(`wrote ${out}: ${runs.map((r) => `${r.id} ${r.lines.length} lines, ${r.verdict}`).join("; ")}`);
